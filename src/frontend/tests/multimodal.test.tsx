it('speech appends only final pieces, stops and handles permission errors', () => {
  type Speech = InstanceType<NonNullable<Window['SpeechRecognition']>>;
  let mic: Speech;
  const start = vi.fn(), stop = vi.fn(() => mic.onend?.()), abort = vi.fn();
  vi.stubGlobal('SpeechRecognition', class { constructor() { mic = this as unknown as Speech; } start = start; stop = stop; abort = abort; });
  const view = render(<App api={new MockApi()}/>);
  fireEvent.change(screen.getByLabelText('민원 설명'), { target: { value: '기존 입력' } });
  fireEvent.click(screen.getByRole('button', { name: /말로 입력/ }));
  expect(start).toHaveBeenCalledOnce(); expect([mic!.lang, mic!.continuous, mic!.interimResults]).toEqual(['ko-KR', true, true]);
  act(() => mic!.onresult?.({ resultIndex: 0, results: [{ isFinal: false, 0: { transcript: '중간' } }] }));
  expect(screen.getByLabelText<HTMLTextAreaElement>('민원 설명').value).toBe('기존 입력');
  act(() => mic!.onresult?.({ resultIndex: 0, results: [{ isFinal: true, 0: { transcript: '가로등' } }] }));
  expect(screen.getByLabelText<HTMLTextAreaElement>('민원 설명').value).toBe('기존 입력 가로등');
  expect(screen.getByRole('button', { name: /듣고 있어요/ }).getAttribute('aria-pressed')).toBe('true');
  fireEvent.click(screen.getByRole('button', { name: /듣고 있어요/ })); expect(stop).toHaveBeenCalledOnce();
  fireEvent.click(screen.getByRole('button', { name: /말로 입력/ })); act(() => mic!.onerror?.({ error: 'not-allowed' }));
  expect(screen.getByRole('alert').textContent).toBe('마이크 권한을 허용해 주세요');
  fireEvent.click(screen.getByRole('button', { name: /말로 입력/ })); view.unmount(); expect(abort).toHaveBeenCalled();
});
