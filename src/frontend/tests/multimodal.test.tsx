it('photo attaches, revokes on removal/unmount and rejects over 10MB', () => {
  const create = vi.fn(() => 'blob:photo'), revoke = vi.fn();
  Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: create }); Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: revoke });
  const view = render(<App api={new MockApi()}/>), input = screen.getByLabelText('사진 첨부', { selector: 'input' });
  const photo = new File(['photo'], 'photo.jpg', { type: 'image/jpeg' });
  fireEvent.change(input, { target: { files: [photo] } }); expect(screen.getByAltText('현장 사진')).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: '제거' })); expect(revoke).toHaveBeenCalledWith('blob:photo');
  const large = new File([], 'large.jpg'); Object.defineProperty(large, 'size', { value: 10 * 1024 * 1024 + 1 });
  fireEvent.change(input, { target: { files: [large] } }); expect(screen.getByRole('alert').textContent).toBe('10MB 이하 사진만 붙일 수 있어요');
  expect(screen.queryByAltText('현장 사진')).toBeNull();
  fireEvent.change(input, { target: { files: [photo] } }); view.unmount(); expect(revoke).toHaveBeenCalledTimes(2);
});
