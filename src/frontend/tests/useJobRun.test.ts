afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks(); });
it('추가 답변을 누적하고 같은 항목은 갱신하며 빈 값은 제외하고 새 제출 때 초기화한다', async () => {
  const api = new MockApi();
  const needsUser = await api.createJob('가로등이 꺼졌어요');
  vi.spyOn(api, 'getTimeline').mockResolvedValue([]);
  const answer = vi.spyOn(api, 'answerJob').mockResolvedValue(needsUser);
  const { result } = renderHook(() => useJobRun(api));
  expect(result.current.answers).toEqual({});
  await act(async () => { await result.current.submit('가로등이 꺼졌어요'); });
  await act(async () => { await result.current.answer({ location_detail: '상도동', category: '가로등', has_photo: '', occurred_at: '   ', q_location_detail: '주민센터 앞' }); });
  expect(result.current.answers).toEqual({ location_detail: '상도동', category: '가로등', q_location_detail: '주민센터 앞' });
  await act(async () => { await result.current.answer({ location_detail: '흑석동', category: '', q1: '건물 앞' }); });
  expect(result.current.answers).toEqual({ location_detail: '흑석동', category: '가로등', q_location_detail: '주민센터 앞', q1: '건물 앞' });
  expect(answer).toHaveBeenLastCalledWith(result.current.jobId, { location_detail: '흑석동', category: '', q1: '건물 앞' });
  await act(async () => { await result.current.submit(sample.inputs.text); });
  expect(result.current.answers).toEqual({});
});
it('동기 완료 응답은 이벤트 순서대로 리플레이하고 마지막에만 결과를 보인다', async () => {
  vi.useFakeTimers();
  const api = new MockApi();
  const { result } = renderHook(() => useJobRun(api));
  await act(async () => { await result.current.submit(sample.inputs.text); });
  expect(result.current.phase).toBe('running');
  expect(result.current.events).toHaveLength(0);
  expect(result.current.result).toBeNull();
  const events = await api.getTimeline(result.current.jobId!);
  const schedule = replaySchedule(events);
  for (let i = 0; i < events.length; i++) {
    await act(async () => { await vi.advanceTimersByTimeAsync(schedule[i] - (i ? schedule[i - 1] : 0)); });
    expect(result.current.events).toEqual(events.slice(0, i + 1));
    expect(result.current.phase).toBe(i === events.length - 1 ? 'success' : 'running');
  }
  expect(result.current.result?.category).toBe('streetlight');
  expect(result.current.stages.every(s => s.status !== 'active')).toBe(true);
});
